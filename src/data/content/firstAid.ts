export function getFirstAidGuides(locale: string): FirstAidGuide[] {
  return locale === 'en' ? en : tr;
}

export function getFirstAidGuide(locale: string, slug: string): FirstAidGuide | null {
  return getFirstAidGuides(locale).find((g) => g.slug === slug) ?? null;
}
