const ev = (
  userId: string,
  source: XpSource,
  amount: number,
  hours: number,
  note: string,
): XpEvent => {
  xpCounter += 1;
  return { id: `xp_${xpCounter}`, userId, source, amount, note, createdAt: hoursAgo(hours) };
};

