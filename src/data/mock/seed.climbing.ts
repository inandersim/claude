type RouteSeed = Omit<
  ClimbingRoute,
  'confirmations' | 'ascentCount' | 'createdAt' | 'verification' | 'submittedBy'
> &
  Partial<Pick<ClimbingRoute, 'confirmations' | 'ascentCount' | 'verification' | 'submittedBy'>> & {
    ageDays?: number;
  };

const sport = (
  id: string,
  cragId: string,
  sectorId: string,
  name: string,
  grade: string,
  o: Partial<RouteSeed> = {},
): RouteSeed => ({
  id,
  cragId,
  sectorId,
  name,
  type: 'sport',
  grade,
  gradeSystem: 'french',
  lengthM: 22,
  pitches: 1,
  bolts: 9,
  stars: 3,
  firstAscent: null,
  description: '',
  ...o,
});

