const now = Date.now();
const daysAgo = (d: number, hour = 9) => {
  const date = new Date(now - d * 86_400_000);
  date.setHours(hour, 0, 0, 0);
  return date.toISOString();
};
const daysAhead = (d: number, hour = 9) => {
  const date = new Date(now + d * 86_400_000);
  date.setHours(hour, 0, 0, 0);
  return date.toISOString();
};
const yearsAgo = (y: number) => new Date(now - y * 365 * 86_400_000).toISOString();

